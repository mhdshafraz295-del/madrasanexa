// Reusable Maps and Sets for O(1) Lookups
export const FEATURE_MAP = Object.freeze(
  new Map(FEATURE_CATALOGUE.map((f) => [f.key, f]))
);

export const FEATURE_KEYS_ALL = Object.freeze(
  FEATURE_CATALOGUE.map((f) => f.key)
);

export const FEATURE_KEYS_IMPLEMENTED = Object.freeze(
  FEATURE_CATALOGUE.filter((f) => f.status === FEATURE_STATUS.IMPLEMENTED).map((f) => f.key)
);

export const FEATURE_KEYS_CORE = Object.freeze(
  FEATURE_CATALOGUE.filter((f) => f.status === FEATURE_STATUS.CORE).map((f) => f.key)
);

export const FEATURE_KEYS_PARTIALLY_IMPLEMENTED = Object.freeze(
  FEATURE_CATALOGUE.filter((f) => f.status === FEATURE_STATUS.PARTIALLY_IMPLEMENTED).map((f) => f.key)
);

export const FEATURE_KEYS_PLANNED = Object.freeze(
  FEATURE_CATALOGUE.filter((f) => f.status === FEATURE_STATUS.PLANNED).map((f) => f.key)
);

const ASSIGNABLE_SET = new Set(FEATURE_KEYS_IMPLEMENTED);

/**
 * Check if a feature key exists in the canonical catalogue
 */
export function isFeatureKeyValid(key) {
  return FEATURE_MAP.has(key);
}

/**
 * Check if a feature is assignable to subscription plans (IMPLEMENTED status only)
 */
export function isFeatureAssignable(key) {
  return ASSIGNABLE_SET.has(key);
}

/**
 * Retrieve a feature definition by key
 */
export function getFeatureByKey(key) {
  return FEATURE_MAP.get(key) || null;
}

/**
 * Get features grouped by category
 */
export function getFeaturesByCategory() {
  return FEATURE_CATEGORIES.map((cat) => ({
    number: cat.number,
    name: cat.name,
    label: cat.label,
    features: FEATURE_CATALOGUE.filter((f) => f.categoryNumber === cat.number),
  }));
}
